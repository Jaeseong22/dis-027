SPAN_AWARE = {"segment_sales"}
_DITTO = "〃(위 행과 병합된 부문 합계)"


def _blank_spans(t, rows):
    """복제된 **수치** 셀을 ditto로 바꾼다. 라벨·텍스트 셀은 그대로 둔다."""
    try:
        grid, n_head, org = P.expand_grid(t.raw or "", with_origins=True)
    except Exception:
        return rows
    # `expand_grid`의 `n_head`는 마크업 기준이다 — `column_names`에 그대로 넘겨
    # `rows_of`와 **같은 헤더 경계**를 쓰게 한다(안 넘기면 추측으로 되돌아간다).
    names = column_names(grid, n_head)
    out, ri = [], n_head
    for lab, vals in rows:
        if ri >= len(grid):
            out.append((lab, vals)); continue
        new_vals = {}
        for k, v in vals.items():
            ci = next((i for i, nm in names.items() if nm == k), None)
            dup = (ci is not None and ri < len(org) and ci < len(org[ri])
                   and not org[ri][ci] and _n(v) is not None)
            new_vals[k] = _DITTO if dup else v
        out.append((lab, new_vals)); ri += 1
    return out


def _table_level(t, rows):
    """데이터 행 **전체가 하나의 병합 셀**인 수치 열을 행에서 떼어 낸다.
    `({열이름: 값}, 남은 rows)`.

    ★ 왜 (2026-08-16, 한화오션 A-7 오답에서): 직원표의 `소속 외근로자 남/여/계`는
      표 전체에 걸린 세로병합이라 **성별·부문과 무관한 전사 값**인데, 행으로 펼치면
      성별 행마다 복제된다. 라벨에 `남`이 들어 있어 "성별 남자 근로자 수"의
      그럴듯한 오답이 된다 — 정답 9,279(`기간의 정함이없는 근로자 전체`) 대신
      15,978(`소속 외근로자 남`)을 답했다(r11·r12 두 회차 동일).

    ★ `_blank_spans`로는 못 고친다. 그쪽은 origin 행 하나에 값을 남기는데
      이 열의 origin이 대부분 첫 데이터 행 = 남 행이다(전수: 51/55사에서 무효).
      값이 **행에 속하지 않으므로 행에서 빼는 것**이 옳다.

    ★ 판별은 값의 동일성이 아니라 **마크업의 병합**으로 한다. "모든 행의 값이 같으면"
      으로 하면 재고 항목이 1종이라 합계=항목인 표(NC `총장부금액`)나 최대주주가
      한 명인 표(LG에너지솔루션 `기말 주식수`)에서 **정답 열을 뺏는다**.
      전수 시뮬레이션으로 확인했다 — 병합 기준은 그 둘을 건드리지 않는다.

    ★ 수치 열만 뺀다(`_blank_spans`와 같은 제한). 텍스트 열(사업부문·품목·투자기간·
      관계)도 병합돼 있지만 오답 원인이 아니고, 빼면 `_disambiguate`가 라벨을 가르는
      데 쓰는 열과 얽힌다.

    전수 실측(70개사 × 정본표 17종): `employees` 167열·56사 ·
    `segment_sales` 1열(레인보우로보틱스 `제품설명`) · `capex` 1열(CJ제일제당 `투자기간`).
    뒤 둘은 값이 전 행 동일이라 옮겨도 손실이 없다.
    """
    try:
        grid, n_head, org = P.expand_grid(t.raw or "", with_origins=True)
    except Exception:
        return {}, rows
    if len(grid) - n_head < 2:            # 데이터 행이 1개면 '전체 걸침'이 무의미하다
        return {}, rows
    names = column_names(grid, n_head)
    lifted = {}
    for ci, nm in names.items():
        origins = [ri for ri in range(n_head, len(grid))
                   if ci < len(org[ri]) and org[ri][ci]]
        if len(origins) != 1:             # 행마다 자기 셀이 있으면 행 수준 데이터다
            continue
        row = grid[origins[0]]
        if ci < len(row) and _n(row[ci]) is not None:
            lifted[nm] = row[ci].strip()
    if not lifted:
        return {}, rows
    return lifted, [(lab, {k: v for k, v in vals.items() if k not in lifted})
                    for lab, vals in rows]


#: `제57기` 같은 기수 표기. 표의 열 이름·행 라벨에 쓰인다.
_PERIOD = re.compile(r"제\s*(\d+)\s*기")


def _year_labels(rows, base_year):
    """열 이름의 `제N기`에 **역년을 박는다** — `제57기` → `2025년(제57기)`.

    ★ 왜: 표에는 기수만 있고 연도가 없다. 모델이 기수를 연도로 옮기다 틀린다 —
      실측(2-6 가동률): 제57기(2025년) 가동률 78.8%를 **2023년**이라고 답했고,
      정작 2025년은 "확인되지 않습니다"라고 했다. 값은 정확히 뽑아 놓고
      연도만 어긋나 오답이 됐다.

    변환 규칙: 보고서의 `base_year`가 **그 표의 최대 기수**에 대응하고, 기수는
    사업연도마다 1씩 증가한다. 그래서 `연도 = base_year - (최대기수 - 기수)`.
    실측으로 확인했다 — 삼성전자 2025/2024/2023 보고서가 각각 제57/56/55기,
    현대자동차가 제58/57/56기로 **오프셋이 기업마다 일정**하다.

    기수가 없으면 아무것도 바꾸지 않는다(추측하지 않는다).
    """
    if not base_year:
        return rows
    ns = set()
    for lab, vals in rows:
        for k in list(vals) + [lab]:
            ns |= {int(m) for m in _PERIOD.findall(k or "")}
    if not ns:
        return rows
    top = max(ns)

    def stamp(s):
        s = s or ""

        def one(m):
            yr = base_year - (top - int(m.group(1)))
            # 이미 그 연도가 적혀 있으면 건드리지 않는다 — 현대자동차 가동률 표는
            # 열 이름이 `2024년 (제57기)`라서, 덧씌우면 `2024년 (2024년(제57기))`가 된다.
            return m.group(0) if str(yr) in s else f"{yr}년(제{m.group(1)}기)"

        return _PERIOD.sub(one, s)

    return [(stamp(lab), {stamp(k): v for k, v in vals.items()}) for lab, vals in rows]


