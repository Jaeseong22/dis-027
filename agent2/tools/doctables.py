_NUMISH = re.compile(r"^[\d,.\-()%\s]*$")


def _disambiguate(rows):
    """라벨이 중복되는 행에 **구분 열 값을 라벨에 합쳐** 유일하게 만든다.

    ★ 왜 필요한가(2026-08-14 실측). 직원표는 `부문 × 성별` **2차원**인데
      라벨이 부문 하나뿐이라 관측에서 남/여가 구분되지 않는다:
          | DX | 37,787 | …      ← 남
          | DX | 12,588 | …      ← 여
      `values()`까지는 `직원 성별: 남`이 값으로 살아 있지만, `_canon()`이
      마크다운 표로 렌더하면 라벨이 첫 열이라 같은 `DX`가 둘이 된다.
      그래서 A-7(성별 남자 근로자수)·A-8(부문별 직원수)이 답을 못 냈다.

    ★ 표별 특수 처리를 하지 않는다 — **12개 표에 걸친 구조적 문제**다(전수):
          major_holders 69사 · auditor 69사 · largest 65사 · raw_materials 25사
          segment_sales 19사 · cashflow 16사 · utilization 12사 · inventory 11사
          capex 10사 · officers 6사 · share_history 3사 · shares 1사
      가르는 열은 표마다 다르지만(성별·구분·주주명) **항상 존재**한다 —
      비수치 열 중 값이 서로 다른 첫 열이다. 그것을 `라벨 · 구분값`으로 합친다.

    라벨이 유일하면 아무것도 하지 않는다(대부분의 표).
    """
    seen = collections.Counter(lab for lab, _ in rows)
    if all(v == 1 for v in seen.values()):
        return rows
    groups = collections.defaultdict(list)
    for i, (lab, vals) in enumerate(rows):
        groups[lab].append(i)
    out = list(rows)
    for lab, idxs in groups.items():
        if len(idxs) < 2:
            continue
        # 구분 열 — 비수치 열 중 그룹 안에서 값이 갈리는 첫 열
        cols = [c for c in rows[idxs[0]][1]
                if not _NUMISH.match(str(rows[idxs[0]][1].get(c) or ""))]
        disc = next((c for c in cols
                     if len({str(rows[i][1].get(c) or "") for i in idxs}) == len(idxs)), None)
        if disc is None:
            continue
        for i in idxs:
            v = str(rows[i][1].get(disc) or "").strip()
            if v:
                out[i] = (f"{lab} · {v}", rows[i][1])
    return out


#: `부문 × 구분` 2차원 표에 **계산된 합계**를 붙일 표. 확정 규칙 4가 "부문별 합산"이라
#: 합계 행이 없는 회사에서는 모델이 직접 더해야 하고, 거기서 틀린다
#: (셀트리온 A-7: 431+313+979를 정확히 나열하고 합을 1,783이라 했다 — 정답 1,723).
