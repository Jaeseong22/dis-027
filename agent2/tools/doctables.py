#: **원문 라벨 오타 보정** — `(기업, 표, 틀린 라벨) → 올바른 라벨`.
#:
#: 한화에어로스페이스 직원표는 같은 방산 부문의 남/여 행을 `방산`·`빙산`으로 적었다.
#: **원문 XBRL도 둘 다 `ACODE="EMP_OPR"`(부문명)로 달아** 격자·속성 어느 쪽으로도
#: 같은 부문임을 알 수 없다(2026-08-18 원문 확인). 편집거리 같은 휴리스틱으로 합치면
#: **멀쩡한 부문을 합칠 위험**이 있어 쓰지 않는다(§2) — 그래서 **사람이 원문을 읽고
#: 확정한 것만** 여기 적는다. 전수 70사 중 이 1건뿐이다.
#:
#: ★ 이 보정이 없으면 `_computed_totals`가 **부문 × 성별 2차원 구조를 인식하지 못한다**
#:   (`항공 · 남`/`항공 · 여`는 성별 접미사가 있는데 `방산`/`빙산`은 없다).
#:   그래서 `방산 · 남+여 합계`(= 5,680)를 못 만들고 A-7·A-8이 계속 틀렸다.
#: ★ **소유권은 여기다.** `goldgen`이 빌려 쓴다 — 사전이 갈라지면 정답과 관측이 어긋난다.
LABEL_TYPO = {("한화에어로스페이스", "employees", "빙산"): "방산"}


def _fix_label_typo(corp, table_id, rows):
    """원문 라벨 오타를 `LABEL_TYPO`대로 고친다. 등록이 없으면 그대로 둔다."""
    if not any(k[0] == corp and k[1] == table_id for k in LABEL_TYPO):
        return rows
    out = []
    for lab, vals in rows:
        head, sep, tail = lab.partition(" · ")
        fixed = LABEL_TYPO.get((corp, table_id, head))
        out.append(((fixed + sep + tail) if fixed else lab, vals))
    return out



def _computed_totals(rows):
    """`부문 · 구분` 표의 두 방향 합계를 계산해 `{라벨: {열: 값}}`으로 돌려준다.

    ★ **가산 가능 열은 데이터로 판정한다** — 원문 합계 행 값 == 부문 행들의 합인
      열만 더한다. 라벨로 가르면(`평균`이 들어가면 제외 등) 내가 기준을 만드는 것이고,
      열 이름은 회사마다 다르다. 전수 실측(70사)에서 자동으로 갈렸다:
          가산 가능  `직 원 수 합 계` 68사 · `기간의 정함이없는 근로자 전체` 67사 ·
                    `기간제근로자 전체` 66사 · `직원 연간급여총 액` 46사
          제외      `직원 1인평균급여액` 64사 · `직원 평 균근속연수` 52사
      **평균 열이 저절로 빠진다.** 안 맞는 열은 그 회사에서 계산하지 않는다(fail-closed).

    ★ 원문 행에 섞지 않고 **별도 필드**로 준다(`values()`의 `표_계산합계`).
      원문에 없는 값이라 표 안에 넣으면 어느 것이 공시된 수치인지 흐려진다.

    합계 행이 없거나 부문이 1개면 아무것도 만들지 않는다 — 그 경우 계산값은
    원문 합계 행과 같아서 중복일 뿐이다.
    """
    tot = [(lab, v) for lab, v in rows if _is_key(lab, _TOTAL_LABELS)]
    seg = [(lab, v) for lab, v in rows if not _is_key(lab, _TOTAL_LABELS)]
    if len(tot) != 1 or len(seg) < 2:
        return {}
    split = [(lab.rsplit(" · ", 1), v) for lab, v in seg]
    if any(len(p) != 2 for p, _v in split):
        return {}                       # `_disambiguate`가 안 갈랐다 = 2차원이 아니다
    parts = [(p[0], p[1], v) for p, v in split]

    # ★ **소계 부문을 뺀다**(§6 측정규칙: 안 빼면 정확히 2배가 나온다).
    #   삼성전자 직원표는 `성별합계`와 `DX`·`DS`가 **같은 층에** 있어 그대로 더하면
    #   128,271이 256,542가 되고, 가산 가능 열 판정이 통째로 실패해 A-8을 못 만든다.
    #   판별은 데이터로 한다 — 그 부문의 값이 **나머지 부문의 합과 같으면** 소계다.
    subtotal = set()
    segs = {d for d, _k, _v in parts}
    for d in segs:
        mine = [v for dd, _k, v in parts if dd == d]
        rest = [v for dd, _k, v in parts if dd != d]
        if not rest:
            continue
        agree = tie = 0
        for c in mine[0]:
            a = [x for x in (_n(v.get(c)) for v in mine) if x is not None]
            b = [x for x in (_n(v.get(c)) for v in rest) if x is not None]
            if not a or not b:
                continue
            tie += 1
            if abs(sum(a) - sum(b)) < 0.5:
                agree += 1
        if tie and agree * 2 > tie:     # 과반 열에서 '나머지의 합'이면 소계다
            subtotal.add(d)
    if subtotal:
        parts = [(d, k, v) for d, k, v in parts if d not in subtotal]

    if len({d for d, _k, _v in parts}) < 2:
        return {}                       # 부문이 1개면 계산값이 합계 행과 같다

    # 가산 가능 열 — 원문 합계 행과 부문 합이 일치하는 열만
    addable = []
    for c in tot[0][1]:
        tv = _n(tot[0][1].get(c))
        svs = [x for x in (_n(v.get(c)) for _d, _k, v in parts) if x is not None]
        if tv is not None and svs and abs(sum(svs) - tv) < 0.5:
            addable.append(c)
    if not addable:
        return {}

    def _sum(sel):
        out = {}
        for c in addable:
            xs = [x for x in (_n(v.get(c)) for v in sel) if x is not None]
            if xs:
                s = sum(xs)
                out[c] = f"{s:,.0f}" if s == int(s) else f"{s:,}"
        return out

    made = {}
    by_kind = collections.defaultdict(list)
    by_seg = collections.defaultdict(list)
    for d, k, v in parts:
        by_kind[k].append(v)
        by_seg[d].append(v)
    for k, sel in by_kind.items():
        if len(sel) > 1:                # 부문이 여럿일 때만 — 1개면 그 행 자체가 답이다
            made[f"전 부문 합계 · {k}"] = _sum(sel)
    for d, sel in by_seg.items():
        if len(sel) > 1:                # 그 부문에 구분이 여럿일 때만
            # ★ 라벨을 `· 계`가 아니라 **무엇의 합인지**로 적는다(2026-08-16 r15 실측).
            #   `전 부문 합계 · 남`은 모델이 그대로 썼는데(A-7 셀트리온 1,723 정답),
            #   `관리사무직 · 계`는 안 쓰고 남 467·여 316을 따로 나열했다(A-8 오답).
            #   `계`만으로는 무엇을 더한 값인지 읽히지 않는다.
            #   ★ 구분자 ` · `는 **하나만** 쓴다 — 라벨을 `rsplit(" · ", 1)`로 되가르는
            #     곳이 있어(검증기 포함) 두 번 들어가면 부문명이 잘린다.
            _ks = "+".join(k for k in dict.fromkeys(k for _d, k, _v in parts if _d == d))
            made[f"{d} · {_ks} 합계"] = _sum(sel)
    return {k: v for k, v in made.items() if v}


def _arith_key(out):
    """핵심행이 **하나도 없을 때**, 산술로 총계인 행을 찾아 핵심행으로 표시한다.

    ★ 왜 (2026-08-16, A-3 오답에서): `inventory`의 `key_rows`는 `('재고자산',)`인데
      총계 라벨이 회사마다 다르다 — 전수로 세니 `합계` 16 · **`총유동재고자산` 14** ·
      `재고자산 합계` 8 · `재고자산` 6 · `합 계`·`유동재고자산`… 10종이었다.
      셀트리온(`합계`)·한화오션(`합계`)은 접두 매칭에 안 걸려 **핵심행이 비었고**,
      `_canon`이 무엇을 앞에 둘지 몰라 정답(장부금액 합계)이 묻혔다.
      A-3 질문의 "총유동재고자산"이 실은 **원문 라벨**(14사)이다.

    ★ 라벨을 열거하지 않는다 — 10종을 적어 두면 새 회사에서 또 샌다.
      **나머지 행의 합과 일치하는 행**을 산술로 찾는다(`_computed_totals`와 같은 규율).
      수치 열의 **과반**에서 성립해야 인정한다(한 열의 우연한 일치를 배제).

    ★ **핵심행이 이미 지정된 표는 건드리지 않는다.** 전수(70사 × 17종) 실측:
      `subsidiary` 70사·`employees` 64사·`largest` 59사는 이미 지정돼 있어 변화 0이고,
      비어 있던 곳에만 붙는다 — `inventory` 36 · `capex` 6 · `utilization` 5 ·
      `share_history` 3 · `raw_materials` 2 · `segment_sales` 1 · `rnd` 1 = **54건**.
      즉 기존 동작을 바꾸지 않는 **순수 추가**다.
    """
    if any(r.get("key") for r in out) or len(out) < 3:
        return out
    cols = set()
    for r in out:
        cols |= set(r["values"])
    cols = [c for c in cols
            if sum(1 for r in out if _n(r["values"].get(c)) is not None) >= len(out) - 1]
    if not cols:
        return out
    for i, r in enumerate(out):
        agree = tie = 0
        for c in cols:
            mine = _n(r["values"].get(c))
            rest = [x for x in (_n(y["values"].get(c)) for j, y in enumerate(out) if j != i)
                    if x is not None]
            if mine is None or not rest:
                continue
            tie += 1
            if abs(mine - sum(rest)) < max(1.0, abs(mine) * 0.001):
                agree += 1
        if tie and agree * 2 > tie:
            r["key"] = True
            # ★ **나머지 행의 값을 잃지 않게 표시해 둔다**(2026-08-16 실측).
            #   `_canon`은 핵심행이 하나도 없으면 `keys = v["rows"]`로 **전 행을 값까지**
            #   보낸다. 여기서 핵심행을 하나 만들면 나머지가 `그 밖의 행`(라벨만)으로
            #   밀린다 — 삼성전자 `segment_sales`에서 DX 부문 매출액 1,879,673이
            #   그렇게 사라졌다(테스트가 잡았다). 총계는 **앞으로 올리되** 나머지 행은
            #   종전처럼 값과 함께 보낸다. `_canon`이 이 표시를 보고 `ROWS_ALL`처럼 다룬다.
            r["key_arith"] = True
            return out                 # 총계는 하나다 — 첫 번째만 표시하고 멈춘다
    return out


def values(corp, table_id, year=None, _tables=None, subtype="annual", month=None):
    """정본 표 → 구조화 dict. 못 찾거나 **검증에 실패하면** None.

    결과는 디스크에 캐시한다(`cache_path`). 캐시는 **None도 기록**한다 —
    "아직 안 해봤다"와 "해봤는데 없다"는 다르고, 후자를 매번 재계산하면
    업종상 표가 없는 기업(재고자산 14사 등)에서 비용을 반복해서 문다.
    """
    import json as _json
    import os as _os
    cp = None
    if _DISK_CACHE and _tables is None:
        # ★ 연도를 **먼저 해소**하고 키를 만든다. `None`과 `2025`가 같은 표인데
        #   키가 갈리면 캐시가 통째로 미스된다. 실측으로 잡았다 — warmup은
        #   `(corp, tid, None)`으로 채웠는데 `find_tables`는 `base` 연도를 해소해
        #   `(corp, tid, 2025)`로 물어서 **적중률 0%**였다(98.5s → 98.8s, 무변화).
        year = year or store.latest_fiscal_year(corp)
        cp = cache_path(corp, table_id, year, subtype, month)
        if _os.path.exists(cp):
            try:
                with open(cp, encoding="utf-8") as fh:
                    return _json.load(fh)
            except (ValueError, OSError):
                pass                       # 깨진 캐시는 무시하고 다시 만든다
    out = _values_uncached(corp, table_id, year, _tables, subtype, month)
    if cp:
        try:
            tmp = cp + ".tmp"
            with open(tmp, "w", encoding="utf-8") as fh:
                _json.dump(out, fh, ensure_ascii=False)
            _os.replace(tmp, cp)           # 원자적 교체 — 반쯤 쓴 파일을 읽지 않는다
        except OSError:
            pass
    return out


def _values_uncached(corp, table_id, year=None, _tables=None,
                     subtype="annual", month=None):
    t = find(corp, table_id, year, _tables=_tables, subtype=subtype, month=month)
    if t is None:
        return None
    check = VERIFY.get(table_id)
    if check is not None and _pin(corp, table_id) is None and not check(t):
        return None                       # fail-closed — 검색 경로로 폴백
    spec = BY_ID[table_id]
    rows = rows_of(t)
    if table_id in SPAN_AWARE:
        rows = _blank_spans(t, rows)
    common, rows = _table_level(t, rows)
    rows = _year_labels(rows, year or store.latest_fiscal_year(corp))
    unit = unit_of(t)
    # ★ 오타 보정은 **`_disambiguate` 앞**이다. 뒤에 두면 이미 늦다 —
    #   `방산`/`빙산`이 서로 다른 이름이라 `_disambiguate`가 "구분 불필요"로 보고
    #   성별 접미사를 안 붙이고, 그러면 `_computed_totals`가 2차원 구조를 못 읽는다.
    rows = _fix_label_typo(corp, table_id, rows)
    rows = _disambiguate(rows)
    computed = _computed_totals(rows) if table_id in COMPUTED_TOTALS else {}
    out = []
    for lab, vals in rows:
        key = _is_key(lab, spec.key_rows)
        out.append({"label": lab, "values": vals, **({"key": True} if key else {})})
    out = _arith_key(out)              # 라벨로 못 잡은 총계 행을 산술로 찾아 표시
    # 핵심행을 앞으로, 그 안에서는 **등록 순서**대로. 절단돼도 중요한 행이 살아남는다.
    out.sort(key=lambda r: (not r.get("key"), _key_rank(r["label"], spec.key_rows)))
    doc = getattr(t, "doc", None) or {}
    return {"table": spec.name, "id": spec.id,
            "section": " > ".join(t.section_path[-2:]),
            **({"출처": _cite(doc)} if doc.get("rcept_no") else {}),
            "unit": unit,
            # 단위를 **문장으로** 함께 준다. unit 필드만 두면 모델이 놓치고 다른 단위로
            # 옮겨 적는다(2-7이 억원 값을 백만원이라 답했다).
            "unit_note": (f"이 표의 모든 수치 단위는 {unit}입니다. 답변에 이 단위를 그대로 쓰십시오."
                          if unit else "단위 표기가 없습니다."),
            "key_rows": [r["label"] for r in out if r.get("key")],
            # ★ **공시가 표 밑에 직접 적어 둔 각주**를 버리지 않는다(2026-08-13).
            #   표만 옮기면 표의 한계를 모른다 — 현대자동차 부문표는 차량·기타만 담는데
            #   각주가 "※ 금융부문 주요 재무정보는 '(금융업)사업의 개요'에 별도 기재함"
            #   이라고 말해 준다. 그 문장이 없어서 1-2가 10회 실행 전부 △였다.
            #   지어낸 규칙이 아니라 회사가 쓴 문장 그대로다(`parse.footnote_after`).
            **({"표_각주": getattr(t, "footnote", "")} if getattr(t, "footnote", "") else {}),
            # ★ 행에 속하지 않는 값(`_table_level`). **키 이름 자체가 경고**여야 한다 —
            #   `소속 외근로자 남`을 "성별 남자 근로자 수"로 읽어 틀린 적이 있다.
            **({"표_공통값(특정 행·부문·성별에 속하지 않음)": common} if common else {}),
            # ★ 계산값은 **원문 행과 섞지 않는다**. 어느 것이 공시된 수치인지 흐려지면
            #   근거 인용이 무너진다. 키 이름에 계산임을 박아 둔다.
            **({"표_계산합계(원문에 없음·아래 행들을 더한 값)": computed} if computed else {}),
            "rows": out,
            "n_rows": len(rows)}


#: 구조적 불변식 — **어느 기업에서나 참이어야 하는 관계**.
#: 기업별 정답을 만들 수 없으므로(70개사 × 표 8종) 이걸로 "맞는 표인가"를 검증한다.
#: 재무에서 `자산 = 부채 + 자본`(IAS 1)을 쓴 것과 같은 방식이다.
#: 깨지면 **그 기업에서 표를 잘못 골랐다는 신호**이고, 값을 몰라도 검출된다.
#: 근거: 템플릿 기반 추출은 기업별 레이아웃 변형에 취약하고 씨앗 과적합 위험이 있다
#: (research/tables.md). 탐지율만으로는 "찾았는가"만 알 뿐 "맞는가"를 모른다.
#: 합계 행 라벨은 기업마다 다르다 — `합 계`·`총 계` 모두 쓰인다(실측).
_TOTAL_LABELS = ("합 계", "합계", "총 계", "총계", "계")

INVARIANTS = {
    "subsidiary": ("상장 + 비상장 = 합계", ("상장", "비상장")),
    "capex": ("부문별 합 = 합계", None),
    "segment_sales": ("부문별 합 = 합계", None),
}


def _n(x):
    """표 셀 → 숫자. `△`·`▲`·괄호를 음수로 읽는다.

    ★ 음수 기호를 놓치면 불변식이 헛돈다 — 삼성전자 부문별 매출의
    `기타 △301,146`(내부거래 제거)을 양수로 읽으면 합계가 60만 넘게 어긋난다.
    """
    t = (x or "").strip()
    if not re.search(r"\d", t):
        return None
    neg = t.startswith(("△", "▲", "-", "−")) or (t.startswith("(") and t.endswith(")"))
    try:
        v = float(re.sub(r"[^\d.]", "", t))
    except ValueError:
        return None
    return -v if neg else v


def check_invariant(corp, table_id, year=None, _tables=None):
    """(설명, 부분합, 합계, 통과여부) 또는 None(불변식 미등록·표 없음·판정불가).

    같은 열에서 부분 행들의 합이 합계 행과 맞는지 본다. 열은 **합계 행에서 숫자가 있는
    열 중 값이 가장 큰 것**을 쓴다 — 기업마다 열 구성이 달라 이름으로 고를 수 없다.
    """
    inv = INVARIANTS.get(table_id)
    if inv is None:
        return None
    desc, parts = inv
    v = values(corp, table_id, year, _tables=_tables)
    if not v:
        return None
    rows = v["rows"]
    tot = next((r for r in rows if _is_key(r["label"], _TOTAL_LABELS)), None)
    if tot is None:
        return None
    cands = {k: _n(x) for k, x in tot["values"].items()}
    cands = {k: x for k, x in cands.items() if x}
    if not cands:
        return None
    col = max(cands, key=lambda k: abs(cands[k]))
    total = cands[col]
    part_rows = [r for r in rows
                 if r is not tot and not _is_key(r["label"], _TOTAL_LABELS)
                 and (parts is None or _is_key(r["label"], parts))
                 and _n(r["values"].get(col)) is not None]
    if not part_rows:
        return None
    ssum = sum(_n(r["values"][col]) for r in part_rows)
    # 허용오차는 **표시 정밀도**에서 나온다 — 행마다 반올림이 half-ulp까지 생기므로
    # 행 수의 절반. 임의의 상대오차(%)를 쓰면 큰 수에서 구멍이 난다(채점기에서 겪었다).
    ok = abs(ssum - total) <= max(len(part_rows) / 2.0, 1)
    return (desc, ssum, total, ok)


def match(query):
    """질의 → 원하는 정본 표 id 목록. 결정론 키워드 매칭.

    ★ **띄어쓰기를 무시하고도 본다** (2026-08-11 실측으로 추가).
      한국어 질의는 띄어쓰기가 자유로운데 종전에는 글자 그대로만 봤다:
          `투자 계획` → ['capex']      `투자계획` → **[]**
      그래서 2-7 문항들이 정본표를 아예 못 탔다. #245 한화오션은 5회 중 4회가
      `find_sections(query=투자계획)`로 빠졌고, `find_tables(query=투자계획)`를
      부른 회차조차 `정본=-`이었다(표를 못 집어서다). #249는 5회 다 X였다.
      값을 정확히 넣어 놔도 **길이 닿지 않으면 소용이 없다.**

      영향은 국소적이다 — 270문항 질의 중 바뀌는 것 **1건**(#249),
      실제 도구 query 52개 중 **1개**(`투자계획`). `docsections`는 0건이라 손대지 않았다.

    ★ **가장 긴 트리거가 맞은 표를 앞에 둔다** (2026-08-14 실측으로 추가).
      종전에는 `TABLES` 등록 순서로 돌려줬다. 그래서 `미등기임원 보수`를 물으면
      `officers`(트리거 `임원`)가 `unreg_officers`(트리거 `미등기임원`)보다 앞서
      **등기임원 표가 나갔다** — A-9가 6회차 내내 0/4였던 이유다.
      더 긴 트리거가 맞았다는 것은 **더 구체적인 질의**라는 뜻이다.

    ★★★ **영문 트리거는 낱말 경계를 요구한다** (2026-08-26 실측으로 추가).
      매칭이 `k.lower() in q`라 **영문 트리거가 다른 영단어 안에 묻혀** 걸렸다.
      `contingent`의 `RG`(선수금환급보증)가 대표적이다:
          `HMM의 merger 관련 공시`   → ['contingent']   (me-**rg**-er)
          `targeting 전략`          → ['contingent']
          `energy storage 관련`     → ['contingent']
          `Morgan Stanley 지분`     → ['contingent']
      코퍼스에 영문 상대처가 흔하고(Nel ASA · Apple · AT&T), 이 오탐은
      `find_tables`·`list_filings`·`loop._canon_assist` 세 경로에 전부 실린다.
      ★ 손실 0으로 확인했다 — 실제 도구 인자 192종 + 질문 534개에서 `RG`의
        **단독 기여가 0건**이다(다른 트리거와 겹치는 1건뿐).
      ★ 한글 트리거에는 걸지 않는다. 한국어는 낱말이 붙어 쓰이고,
        `현금·현물배당결정`의 `배당`처럼 **묻혀 있어도 같은 뜻**인 경우가 정상이다.
    """
    q = (query or "").lower()
    qz = _SP.sub("", q)
    hits = []
    for t in TABLES:
        best = max((len(k) for k in t.triggers if _trigger_hit(t.id, k, q, qz)),
                   default=0)
        if best:
            hits.append((best, t.id))
    hits.sort(key=lambda x: -x[0])
    return [tid for _, tid in hits]


#: 순수 ASCII 트리거(영문·숫자). 이런 것만 낱말 경계를 요구한다.
_ASCII_TRIG = re.compile(r"^[A-Za-z0-9&./-]+$")

#: ★★ **글자는 같은데 뜻이 다른 자리** — 트리거별 부정 문맥. `(표, 트리거) → 무효화 어휘`.
#:
#:   `raw_materials`의 트리거 `조달`(원재료 조달)이 **`자금조달`**에 걸린다.
#:   그래서 "자금조달 내역을 유형별로 정리해줘"(주최 예시 질의 Q-4)에 **원재료 매입 현황**
#:   표가 관측 앞자리를 차지했다.
#:
#:   ★ **트리거를 지우지 않고 무효화만 한다.** 실제 도구 인자 192종 + 질문 534개에서
#:     `조달`의 단독 기여는 **2건이고 둘 다 자금조달**(= 전부 오탐)이지만, `소재 조달`처럼
#:     정당한 미래 질의까지 잃을 이유는 없다. 트리거는 남기고 **그 자리만** 끈다.
#:   ★ 부정 문맥은 **표 전체가 아니라 그 트리거 하나**에만 건다. 표에 걸면
#:     "자금조달 계획과 원재료 매입 현황"에서 `원재료`까지 함께 죽는다.
#:   ★ 경계로는 못 고친다 — 한국어라 `자금조달`과 `원재료 조달`의 형태가 같다.
#:     가르는 것은 뜻이고, 뜻은 데이터로 등록한다(§3·§5).
_ANTI_TRIGGER = {
    ("raw_materials", "조달"): ("자금조달", "자금 조달"),
}


def _trigger_hit(tid, k, q, qz):
    """트리거 하나가 질의에 걸리는가. 낱말 경계와 부정 문맥을 함께 본다."""
    kl = k.lower()
    if _ASCII_TRIG.match(k):
        # 앞뒤가 영숫자면 더 긴 영단어의 일부다(merger 안의 rg).
        if not re.search(r"(?<![a-z0-9])" + re.escape(kl) + r"(?![a-z0-9])", q):
            return False
    elif kl not in q and _SP.sub("", kl) not in qz:
        return False
    return not any(a.lower() in q or _SP.sub("", a.lower()) in qz
                   for a in _ANTI_TRIGGER.get((tid, k), ()))


