        #   ★ 합계는 **배치가 자르기 전 전 행으로** 계산해 둔 값을 쓴다. 여기서 다시
        #     더하면 잘린 12행만 더해 부분합이 된다(셀트리온 특별관계자 105명).
        sums = {k: f"{v['sum']:,} ({v['n']}행 합산)"
                for k, v in (t.get("col_sums") or {}).items()}
        if sums and _is_roster:            # ★ 명부표일 때만. 위 `_is_roster` 주석 참조.
            block["전 행 합계(보고자 + 특별관계자 전원)"] = sums
