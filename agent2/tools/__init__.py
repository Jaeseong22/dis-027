        #   **약칭·영문**이라 "보고자 성명(명칭)"의 답이 아니다 — 전수 70사 중 **20사**가
        #   필드 표기와 다르다(`삼성물산` vs `삼성물산주식회사` · `(주)셀트리온홀딩스` vs
