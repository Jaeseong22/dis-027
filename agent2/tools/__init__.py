# 종전에는 `find_sections`에만 등록돼 있어 커버리지 보고가 "산문 섹션으로 답한다"고 말했다.
# (런타임에는 영향이 없다 — `scenarios`는 `registry.scenario_coverage`만 쓴다. 표기 정정이다.)
@tool("1-3", "1-7", "1-8", "1-9", "1-12", "1-14", "1-15", "1-16", "1-17", "1-18", "2-3")
def find_tables(corp: str, query: str, year: int = None, k: int = 4,
                years: int = 1) -> list:
    """공시에서 표를 찾는다. 자주 쓰는 표는 라벨·값·단위로 파싱해서 함께 돌려준다.

    주식의 총수 · 직원 등의 현황 · 연결대상 종속회사 · 최대주주 · 시설투자 · 가동률은
    정본 표를 결정론으로 찾아 rows(라벨→값)와 unit을 줍니다. 이 값을 그대로 쓰십시오.

    ★ 재무제표 표준 수치(매출·영업이익·순이익·자산·부채·자본·판관비·현금흐름·주당이익)는
    get_financials나 financial_series를 쓰십시오.

    예: "주식의 총수" "최대주주 현황" "직원 현황" "1인평균 급여액" "우선주 발행"
    "생산능력 가동률" "시설투자" "유상증자 무상증자 이력" "재고자산" "현금흐름표"

    인자:
        corp: 기업명
        query: 찾을 내용을 한국어로. 공시 용어에 가까울수록 정확하다
        year: 사업연도. 안 주면 최신
        k: 표 몇 개까지
        years: 최근 몇 개년의 표를 모을지. 3개년 추이 질의는 3으로 주십시오

    반환:
        [{section, table, unit, unit_note, key_rows, rows, year}] 정본표 +
        [{section, html, score}] 검색 결과
    """
    k = min(k or _KMAX, _KMAX)
    # ① 어떤 정본표가 걸리는지 먼저 정한다
    name, _miss = _no_corp(corp)
    if _miss:
        return [_miss]
    fin = _fin_block(name, query, year)
    base = year or _store.latest_fiscal_year(name) or 0
    # ★★ **질의가 분기·반기보고서를 지목하면 그 보고서를 본다**(2026-08-17).
    #   주최 참고용 질의 "2026년 1분기 **분기보고서를 기준으로** 주요 투자 계획을
    #   정리해줘"를 종전에는 통째로 못 받았다 — `_tables_of`가 `annual` 하드코딩이었다.
    #   라우팅은 **질의 문자열**로 한다(도구 인자를 늘리면 기존 인자가 밀린다 · §6-14).
    #   ★ 오탐 위험을 전수로 쟀다: 기존 정답셋(4사 115 + 8사 228) 질의에 `분기|반기`가
    #     **0건**이다. 주최 예시 6종 중에서는 정확히 1종만 걸린다.
    sub, mon = _periodic_of(query)
    # ★★ **분기·반기는 연도도 따라가야 한다**(2026-08-23). 위 `base`는
    #   `latest_fiscal_year`(= `annual` 전용)라 **2025**다. 2026년 1분기를 물었는데
    #   2025년 1분기 표를 봤다 — 라우팅이 `subtype`만 바꾸고 연도를 안 바꿨다.
    #   전수: 70사 전부 `quarter` 최신이 **2026**이고 `annual` 최신은 2025다.
    if not year and sub != "annual":
        base = _store.latest_base_year(name, sub) or base
    matched = _doctables.match(query)
    found = [(y, v) for tid in matched
             for y in range(base - years + 1, base + 1)
             if (v := _doctables.values(name, tid, y, subtype=sub, month=mon))]

    # ★★ **정본표가 걸렸는데 그 회사에 없으면 정형공시로 대체한다**(2026-08-17).
    #   전수: `capex`(설비투자) 정본표는 **36/70사**뿐이다. 없는 34사 중 20사는
    #   `생산설비` 섹션이 있는데도 표가 **유형자산 보유 명세**뿐이고 투자 계획 표가 없다
    #   (섹션 제한을 풀면 `투자` 시그니처가 34/34사에서 수십 개 맞는다 — §6-10대로
    #    셀 시그니처만으로는 못 고른다).
    #   대신 거래소 `신규시설투자등` 공시가 43건·21사이고 필드가 완전하다
    #   (`2. 투자내역 > 투자금액(원)` 43/43). 그중 **capex 표가 없는 5사**를 덮는다.
    #   확정 규칙 10(거래소 원문 없는 배당 → 사업보고서 대체)의 **반대 방향** 대체다.
    alt = []
    for tid, ftype in _CANON_FALLBACK.items():
        if tid in matched and not any(True for _y, v in found if v.get("id") == tid):
            rec = _filing_record(name, ftype)
            if rec:
                rec = {"※": f"`{_doctables.BY_ID[tid].name}` 정본표가 이 회사에는 "
                            f"없습니다. 같은 사실을 담은 **{ftype}** 공시로 대체합니다.",
                       **rec}
                alt.append(rec)

    # ② 검색 결과를 먼저 만든다 — 정본표가 있으면 HTML 없이 목록만
    hits = _search.search(query, corp=corp, year=year, kind="table", k=k)
    # ★★ **`fin`(재무표준값)만으로는 검색 표를 죽이지 않는다**(2026-08-23 수정).
    #   종전은 `bool(found or fin)`이었다. 그러면 정본표가 **하나도 안 걸려도**
    #   `fin` 블록 하나 붙었다는 이유로 검색 결과가 **제목+점수만** 남고 표 내용이 통째로 빠진다.
    #   실측(r38): 현대건설 "공사손실충당부채"에서 검색이 `III. 재무에 관한 사항 > 16. 충당부채`를
    #   **1위(41.6점)로 정확히 찾았는데** 관측에는 그 제목만 나갔다. `fin`은 질문과 무관한
    #   `liabilities_total` 하나뿐이었다. 모델은 값을 못 보고 "확인할 수 없습니다"로 물러섰다.
    #   같은 형태로 r38 73문항 중 **24건이 기권**했다.
    #   예산 절약이라는 원래 취지는 **정본표가 답을 담고 있을 때** 성립한다 —
    #   `fin`은 재무제표 표준 수치 몇 개뿐이라 그 근거가 안 된다.
    #   영향 범위(정답확정 301문항 전수): 정본표 없이 `fin`만 붙는 문항 **20건**.
    has_canon = bool(found)
    rest = []
    for i, h in enumerate(hits[:3 if has_canon else k]):
        sec = " > ".join(h.unit.section_path[-2:])
        # ★ 정본표가 있어도 **1위 본문은 남긴다**(`KEEP_TOP_SNIPPET` 주석 참조).
        body = (not has_canon) or (KEEP_TOP_SNIPPET and i == 0)
        rest.append({"section": sec, "score": round(h.score, 2), "source": "검색",
                     "html": h.unit.table.to_html(max_rows=25) if h.unit.table else ""}
                    if body else
                    {"section": sec, "score": round(h.score, 2), "source": "검색(목록)"})
    if fin:
        rest.append(fin)
    rest = alt + rest

    # ③ 남는 공간을 정본표에 배분한다(추정하지 않고 실측)
    bud = _canon_budget(rest, len(found))
    out = [_canon(v, year=y, budget=bud, query=query) for y, v in found]
    if fin:
        out.append(fin)
        rest = [x for x in rest if x is not fin]
    return _fit(out, rest)


#: ★★★ **정본표가 걸려도 검색 1위의 본문은 남긴다**(2026-08-26).
#:
#:   종전에는 정본표가 **하나라도** 걸리면 검색 결과가 `제목+점수`만 남았다(`검색(목록)`).
#:   질문이 정본표가 담지 않는 것을 **함께** 물으면 그 부분은 영영 못 답한다:
#:       검색-19  "삼성생명 CSM **및** K-ICS 비율"
#:                match → `solvency` → has_canon=True → 검색 본문 삭제
#:                `solvency`엔 K-ICS 198.0만 있고 **CSM 13,232,616은 없다**
#:                검색은 `15-3. 보험계약자산 및 보험계약부채`를 정확히 찾아냈다(제목만 나갔다)
#:   ★ **검색이 못 찾는 게 아니다** — 삼성화재 `해약환급금준비금`은 56.1점 1위다.
#:     버리는 쪽이 문제였다.
#:   ★ 이 병은 2026-08-23에 **`fin`(재무표준값)에 대해서만** 고쳐져 있었다
#:     (*"정본표 없이 fin만 붙는다는 이유로 검색 표가 죽어 r38 73문항 중 24건이 기권"*).
#:     같은 논리가 `found`(정본표)에도 그대로 성립하는데 그쪽은 안 고쳤다.
#:   ★ **1위만** 남긴다. 전부 남기면 관측 예산을 정본표에서 뺏는다 —
#:     이 저장소가 반복해 겪은 실패다(§6-14). 나머지는 종전대로 목록이다.
#:   ★ `_fit`이 상한을 지키므로 넘치면 정본표 핵심행이 아니라 **산문이 먼저 줄어든다**.
#:
#: ★★★ **r52에서 실측으로 기각했다. 기본은 끈다**(2026-08-26).
#:   결정론 측정은 좋았다 — 질문 400개 전수에서 새 수치 +1,469/+5,387 · **정답 도달이
#:   나빠진 문항 0건**. 그런데 종단(도메인 검수자 73문항 1회)에서는 이득이 안 나왔다:
#:     겨냥 집합(정본표가 질문 일부만 덮는 보험 3문항 검색-19·23·복합-20)  **개선 0건**
#:     KEEP_TOP이 관측을 실제로 바꾼 문항  **1건뿐**(검색-71 12,113 → 13,996자)
#:     그 1건의 판정  **O → X**(부재형: 부재를 밝히지 않음)
#:   즉 **귀속 가능한 이득 0 · 귀속 가능한 손해 1**이다. §5.2의 판정 규칙 그대로
#:   ("총점 1회로 판정하지 말고 겨냥 집합으로 판정하라") 겨냥이 안 붙었으므로 끈다.
#:
#: ★★ 왜 손해가 났나 — **부재형과 충돌한다.** 검색-71은 정답이 `공시에 기재되지 않음`인데
#:   ※가 "매출 구성은 있고 신작 출시일·분기 연결 서술만 없다"고 한다. 본문이 더 실리자
#:   모델이 매출 구성으로 답을 만들고 **부재 선언을 빼먹었다.**
#:   §6-8 그대로다 — 겨냥한 축(도달)은 좋아지고 다른 축(부재형)이 무너진다.
#: ★ **되살리려면 부재형 처방을 함께 넣어야 한다** — "확인된 것을 제시하되 없는 것을
#:   반드시 짚어라"(SYSTEM 규칙 11이 이미 그렇게 적혀 있는데 안 지켜진다).
#:   재료를 넣는 것과 그 재료를 어떻게 쓰게 할지는 **다른 문제**다.
#: 켜려면 `A2_KEEP_TOP=1`.
KEEP_TOP_SNIPPET = (_os.environ.get("A2_KEEP_TOP") or "0") != "0"


#: 질의 → (정기공시 종류, 기준월). 코퍼스 전수 실측으로 월을 못 박았다 —
#: `quarter`는 3월·9월, `half`는 6월, `annual`은 12월뿐이다(quarter 529·half 234·annual 291).
#: 그래서 "1분기"=3월 · "3분기"=9월 · "반기/상반기"=6월로 정확히 갈린다.
#:
#: ★★★ **2분기·4분기가 빠져 있었다**(2026-08-26). 코퍼스에 실재하는 조합은 넷뿐이다:
#:     (quarter, 3) 303 · (half, 6) 234 · (quarter, 9) 226 · (annual, 12) 291
#:   `2분기`는 어느 패턴에도 안 걸려 `annual`로 떨어졌다 — **반기보고서 234건이
#:   멀쩡히 있는데 사업보고서를 봤다.** `4분기`도 `annual`로 가는데 그건 맞다
#:   (4분기 단독 보고서가 없고, 그 기간을 담은 것이 사업보고서다).
#:   ★ `2분기 → half(6)`는 "2분기 단독"이 아니라 **코퍼스에서 가장 가까운 보고서**다.
#:     상반기 누적이라는 사실은 `unit_note`·표 제목에 그대로 남는다.
#:   ★ 현재 정답셋 534문항에 `2·4분기` 표현이 **0건**이라 측정으로는 안 걸렸다.
#:     주최 평가셋은 비공개이므로 안 걸렸다는 것이 없다는 뜻은 아니다.
_PERIODIC_Q = (
    (_re.compile(r"1\s*분기|첫\s*분기"), ("quarter", 3)),
    (_re.compile(r"3\s*분기"), ("quarter", 9)),
    (_re.compile(r"2\s*분기"), ("half", 6)),
    (_re.compile(r"4\s*분기"), ("annual", 12)),
    (_re.compile(r"반기|상반기"), ("half", 6)),
    (_re.compile(r"분기보고서|분기\s*기준"), ("quarter", None)),
)


def _periodic_of(query):
    """질의가 지목한 정기공시 종류. 없으면 사업보고서(`annual`)다.

    ★ **못 찾으면 사업보고서로 물러나지 않는다** — `_tables_of`가 그 종류에서만 찾고
      없으면 None을 낸다(fail-closed). 분기를 물었는데 연간 수치를 주면 어느 보고서의
      값인지 흐려진다(§6-10 "셀 내용만으로 표를 고르면 틀린다"와 같은 규율).
    """
    q = str(query or "")
    for pat, (sub, mon) in _PERIODIC_Q:
        if pat.search(q):
            return sub, mon
    return "annual", None


@tool("1-2", "1-13", "2-2", "2-3", "2-4", "2-5", "2-6", "2-7")
def find_sections(corp: str, query: str, year: int = None, k: int = 4) -> list:  # noqa: D401
    """공시의 서술 섹션을 찾아 본문을 돌려준다. 설명이나 현황을 묻는 질의에 쓴다.

    ★ 재무제표 수치(매출·영업이익·순이익·자산·부채·자본·판관비·현금흐름·주당이익)는
    get_financials를 쓰십시오. 이 도구가 돌려주는 본문에는 연결과 별도 재무제표가
    함께 들어 있어 별도 값을 연결로 잘못 읽기 쉽습니다.

    예: "주요 제품 및 서비스" "원재료" "생산설비 가동률" "설비의 신설 계획"
    "사업의 개요" "경쟁 현황" "사업장 현황" "직원 등의 현황"

    인자:
        corp: 기업명
        query: 찾을 내용을 한국어로
        year: 사업연도. 안 주면 최신
        k: 섹션 몇 개까지

    반환:
        [{section, text, score}] — text는 섹션 본문
    """
    k = min(k or _KMAX, _KMAX)
    # 정본 표가 걸리면 함께 준다 — 표 질의를 find_sections로 물어오는 경우가 실제로 있다
    # (1-11 연결대상 종속회사를 find_sections만 불러 상장/비상장을 못 냈다).
    name, _miss = _no_corp(corp)
    if _miss:
        return [_miss]
    fin = _fin_block(name, query, year)
    found = [v for tid in _doctables.match(query)
             if (v := _doctables.values(name, tid, year))]
    # ★ **정본 섹션(산문)도 같은 방식으로 붙인다**(2026-08-06).
    #   답이 표가 아니라 문단에 있는 질의를 통째로 놓치고 있었다 — 270문항 서술형
    #   35건 중 25건이 이 경로다. BM25로는 못 집는다(실측: 삼성전자 "공장 생산거점"
    #   1위가 가동률 표, 삼성생명 "IFRS17"이 태국 자회사 절).
    secs = [v for sid in _docsections.match(query)
            if (v := _docsections.values(name, sid, year, limit=_SEC_LIMIT))]
    hits = _search.search(query, corp=corp, year=year, kind="section", k=k)
    # ★ `secs`를 여기 넣으면 안 된다. `has_canon`은 **검색 결과의 본문을 버릴지**를
    #   정하는데, 정본표·재무값과 달리 섹션 산문은 표 수치를 대체하지 못한다.
    #   실측 회귀: 넣었더니 2-5(원재료)가 3/8 → 0/8로 무너졌다 — 매입 비중
    #   91.4%가 검색 본문에만 있었는데 그게 목록으로 바뀌어 사라졌다.
    # ★ **`fin`이 답을 대체하지 못하는 질의가 있다**(2026-08-12 실측).
    #   `_fin_block`은 재무제표 **표준 수치**(전체 매출액 등)를 준다. 그런데 질의가
    #   `부문별 매출 비중`처럼 **분해**를 물으면 전체 매출액은 답이 아니다.
    #   그런데도 `has_canon=True`가 되어 검색 본문이 목록으로 바뀌고, 그 결과
    #   1-2 다섯 개사가 전부 "확인되지 않습니다"로 후퇴했다(2회 재현):
    #       HD현대중공업 조선 70.89%는 `1. 사업의 개요` **표**에 있다.
    #       정본표 `segment_sales`는 이 회사에서 의도적으로 기권한다
    #       (당시 13/70사 · **2026-08-14 필수 셀 완화 후 42/70사**).
    #       정본섹션은 산문만 주고 표를 뺀다(그 note에 명시돼 있다).
    #       → 세 경로가 모두 값을 안 주는데 검색 본문까지 버려졌다.
    #   같은 논리가 위 `secs` 주석에도 적혀 있다 — "표 수치를 대체하지 못한다".
    #   `fin`도 **분해 질의에서는** 대체하지 못한다.
    has_canon = bool(found or (fin and not _FIN_NOT_ENOUGH.search(query or "")))
    rest = []
    for i, h in enumerate(hits[:3] if has_canon else hits):
        sec = " > ".join(h.unit.section_path[-2:])
        body = (not has_canon) or (KEEP_TOP_SNIPPET and i == 0)
        rest.append({"section": sec, "score": round(h.score, 2), "source": "검색",
                     "text": h.unit.text[:_SNIPPET]} if body else
                    {"section": sec, "score": round(h.score, 2), "source": "검색(목록)"})
    if fin:
        rest.append(fin)
    # 섹션이 차지할 자리를 **미리 반영해** 표 예산을 잡는다. 안 그러면 나중에
    # `_fit`이 표의 핵심행부터 깎는다(실측: 기아 원재료 매입액이 그렇게 잘렸다).
    bud = _canon_budget(rest + secs, len(found))
    out = [_canon(v, budget=bud, query=query) for v in found]
    out.extend(secs)                      # 정본 섹션은 이미 잘라 왔다(_SEC_LIMIT)
    if fin:
        out.append(fin)
        rest = [x for x in rest if x is not fin]
    return _fit(out, rest)


