#: 재무구조 비율 — **업계 표준 정의**다(§3: 기준을 스스로 만들지 않는다).
#:   부채비율   = 부채총계 ÷ 자본총계 × 100      (K-IFRS 재무비율 관행 · 금감원 전자공시 기준)
#:   자기자본비율 = 자본총계 ÷ 자산총계 × 100
#:   유동비율   = 유동자산 ÷ 유동부채 × 100
#: ★ 왜 코드가 계산하나: r44 검색-15에서 `get_financials`가 부채총계 42,814,746,926,182원 ·
#:   자본총계 62,377,691,037,383원을 **정확히 줬는데** 모델이 `calculate`를 부르고도
#:   68.6%를 못 냈다. §7 "수치는 결정론 코드, 서술은 LLM"이다 — 나눗셈을 모델에 시키지 않는다.
#: ★ 분모가 0이거나 없으면 **내지 않는다**(`_sales_ratios`와 같은 규율 — 정직한 부재).
_STRUCT_RATIO = (
    ("부채비율", "liabilities_total", "equity_total"),
    ("자기자본비율", "equity_total", "assets_total"),
    ("유동비율", "current_assets", "current_liabilities"),
)


def _struct_ratios(allvals):
    """재무구조 비율(%). 필요한 두 항목이 다 있을 때만 낸다."""
    out = {}
    for name, num, den in _STRUCT_RATIO:
        a, b = allvals.get(num), allvals.get(den)
        if a is None or not b:
            continue
        try:
            out[name] = f"{a / b * 100:.1f}%"
        except (TypeError, ZeroDivisionError):
            continue
    return out


def _sales_ratios(asked, allvals):
    """질의에 걸린 손익 항목의 **매출액 대비 비율(%)** — 코드가 계산한다.

    ★ 분모는 **`revenue`뿐이다.** top-line 대체(순이자손익·보험영업수익)를 분모로 쓰면
      값이 나오긴 하는데 뜻이 없다 — 실측: KB금융 판관비율이 **−57.1%**로 나왔다
      (순이자손익이 분모라 부호까지 뒤집혔다). '매출액 대비'라는 이름이 성립하지 않는
      업종에서는 **비율을 내지 않는다.** 정직한 부재가 그럴듯한 오답보다 낫다.
    """
    top = allvals.get("revenue")
    if not top or top <= 0:
        return {}
    out = {}
    for cid, name in _SALES_RATIO.items():
        v = asked.get(cid)
        if v is None:
            continue
        try:
            out[name] = f"{v / top * 100:.1f}%"
        except (TypeError, ZeroDivisionError):
            continue
    return out


#: 표 단위에서 금액 단위만 뽑는다(`억원, %` → `억원`).
#: **금액 단위만**. 고치려는 혼동은 `억원 vs 백만원`이라는 배수 문제이고,
#: 개수 단위(명·주·건)엔 그런 혼동이 없다. 실측: 개수까지 붙였더니 1-16(직원수)이
#: 3/3 → 0/3으로 무너졌다(1-2는 0/3 → 3/3으로 해결).
_MONEY_UNIT = _re.compile(r"(조원|십억원|억원|백만원|천원|천만원|원)")
_NUMCELL = _re.compile(r"^[\d,]+(\.\d+)?$|^[(△▲-][\d,]+(\.\d+)?\)?$")


#: 단위 인라인 on/off. A/B용.
UNIT_INLINE = True


#: 열 이름이 **금액임을 적극적으로 가리킬 때만** 단위를 붙인다.
#: ★ 캡션 단위를 표 전체에 적용했다가 1-16을 깼다 — 직원 표는 캡션이 `(단위: 백만원)`인데
#:   `명`·`년`·`백만원` 열이 **섞여 있다.** 그 결과 `직원수 128,881 백만원`,
#:   `근속연수 13.7 백만원`이 되어 모델이 그대로 받아 적었다.
#:   틀린 단위를 붙이는 것은 안 붙이는 것보다 나쁘다 — 그래서 **화이트리스트**로 간다
#:   (놓치면 unit_note가 받고, 잘못 붙이면 오답이 된다).
_MONEY_COL = _re.compile(r"액|금액|매출|투자|급여|자산|부채|자본|수익|비용|원가|대금|가액")


#: **표 전체가 하나의 금액 단위인 정본표.** 여기 등록된 표는 열 이름과 무관하게
#: 모든 수치 셀에 단위를 붙인다.
#:
#: ## 왜 열 이름 화이트리스트만으로는 안 되나 (2026-08-08 RUN 1 실측)
#:
#: 연결 현금흐름표의 열 이름은 **기수**(`제 82 기`)라 `_MONEY_COL`에 걸리지 않는다.
#: 그래서 단위가 값과 분리된 채 모델에게 갔고, 모델이 재조립하다 자릿수를 틀렸다.
#: 시나리오 1-3 오답 8건 중 **6건**이 이 형태다:
#:     기아        도구 `9,054,140`(백만원)      → 답변 `90,541,400백만원`     자릿수 +1
#:     현대자동차   도구 `(5,991,270)`(백만원)    → 답변 `-59,912,700,000원`    환산 실패
#:     HD현대중공업 도구 `3,510,392,442`(천원)    → 답변 `35,103,924,420천 원`  자릿수 +1
#:     한화오션·삼성생명·KB금융                   → 억원으로 절사
#: 값 자체는 맞았다. **전달 구간에서 깨진다**(arXiv 2410.11781: LLM은 숫자를 자릿수
#: 단위로 인코딩해 편집거리는 가깝고 값은 먼 오류를 낸다).
#:
#: ## 왜 표별로 등록하나 — 전체 적용은 이미 한 번 깨졌다
#:
#: `_MONEY_COL` 화이트리스트가 있는 이유가 아래 주석에 적혀 있다(직원 표에 캡션 단위를
#: 통째로 붙였다가 `근속연수 13.7 백만원`이 됐다). 그래서 **단일 금액 표만** 고른다.
#: 70개사 전수 실측(2026-08-08):
#:     cashflow    70/70사 보유 · 비금액 의심 셀 **0건**   ← 열이 전부 기수
#:     inventory   56/70사 보유 · 비금액 의심 셀 **0건**   ← 취득원가·충당금·장부금액
#:                 ★ 2026-08-14에 필수 셀을 `평가충당금`→`충당금`으로 넓혀 46→56이 됐다.
#:     employees   70/70사 보유 · 비금액 의심 셀 **297건** ← 평균근속연수 17.4 등. 제외
#: 표를 추가하려면 같은 전수 검사를 먼저 돌릴 것.
_MONEY_TABLE = {"cashflow", "inventory"}


def _with_unit(values, unit, table_id=None):
    """**금액 열의** 수치 셀에 단위를 붙여 준다. 값과 단위를 떼어 놓으면 모델이 섞는다.

    실측(1-2): `unit_note`로 "이 표의 단위는 억원"이라고 문장으로 줬는데도
    모델이 `1,879,673 백만원`이라 답했다. 같은 관측에 재무표준값(백만원)이 함께
    있어서다. 단위를 값 옆에 붙이면 그 혼동이 생길 자리가 없어진다.
    비율(%)·텍스트 셀은 건드리지 않는다.

    `table_id`가 `_MONEY_TABLE`이면 **열 이름을 보지 않는다**(위 주석 참조).
    """
    if not UNIT_INLINE:
        return values
    m = _MONEY_UNIT.search(unit or "")
    if not m:
        return values
    u = m.group(1)
    all_money = table_id in _MONEY_TABLE
    return {k: (f"{x} {u}"
                if (all_money or _MONEY_COL.search(k or ""))
                and _NUMCELL.match((x or "").strip())
                else x)
            for k, x in values.items()}


#: **모든 행이 핵심인 표.** 여기 없는 표는 종전대로 핵심행만 값을 싣고 나머지는 라벨만 준다.
