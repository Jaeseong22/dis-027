#: ★★ **"합계 열을 늘 앞으로" 규칙은 실측으로 기각했다**(2026-08-24 · §6-8).
#:   동기는 r49 검색-8이었다 — 현대모비스 `related_party`가 전치형이라 합계 열이 뒤에 있고
#:   모델이 첫 거래처 값(1,150,407)을 답했다(정답 합계 50,114,735).
#:   그런데 394문항 전수 diff에서 **정답 위치가 앞으로 온 문항 0 · 뒤로 밀린 문항 3**이었고
#:   현대모비스 자신도 안 고쳐졌다(1,150,407이 여전히 앞). 순손실이라 걷어냈다.
def _col_score(col, qn):
    """열 이름이 질문 어휘와 얼마나 맞나. 0=무관 · 1=2자 겹침 · 2=3자 이상 · 3=이름 전체."""
    c = _re.sub(r"\s+", "", str(col or ""))
    if not c or not qn:
        return 0
    if c in qn:
        return 3
    for L in range(len(c), 1, -1):
        for i in range(len(c) - L + 1):
            if c[i:i + L] in qn:
                return 2 if L >= 3 else 1
    return 0


def _num_like(x):
    """그 셀이 **수치 셀**인가. ★ `_with_unit`이 붙인 단위 접미를 받아야 한다.

    ★★ 처음엔 정규식이 숫자+콤마+% 만 허용하는 전체 일치였는데, 값이 `50,114,735 백만원`이면
      매치가 안 됐다 — 단위가 붙는 표에서는 `_order_cols`가 **아예 동작하지 않았다.**
      실측(r49 검색-8): 현대모비스 합계 열 이름이 `전체 특수관계자 합계`로 정렬 대상인데
      단위 접미 때문에 수치 열로 안 잡혀 맨 뒤에 남았고, 모델이 첫 거래처 값을 답했다.
    """
    t = str(x or "").strip()
    m = _re.match(r"^\(?-?[\d,]+(?:\.\d+)?\)?", t)
    if not m:
        return False
    return len(t[m.end():].strip()) <= 6      # `백만원`·`%`·`주`·`명` 등


def _order_cols(vals, query):
    """★★★ **질문이 부른 이름의 열을 맨 앞으로 올린다**(2026-08-24).

    r45 실측 — 정답이 관측에 있고 **열 이름까지 정확히 붙어 있는데** 모델이
    **행의 마지막 열**을 읽었다. 두 문항이 같은 모양이었다:

        검색-58 삼성E&A  질문 '지분법 손익'
            Nel ASA → {기초 '-', 취득 47,629,124, **지분법손익 9,768,493**,
                       기타증감 (790,356), 당기말 56,607,261}   → 모델은 `당기말`을 답했다
        검색-59 대우건설  질문 '미청구공사 **잔액**'
            미청구공사 → {**채권잔액 937,999**, 대손충당금 (115), 장부금액 합계 937,884}
                                                              → 모델은 `장부금액 합계`를 답했다

    §6-34("dict 삽입 순서가 그대로 관측 순서가 된다")의 뒷면이다 — 순서가 있는데
    **마지막이 이긴다.** 그래서 순서를 질문 쪽으로 돌린다.

    ★ **버리지 않는다. 순서만 바꾼다** — 그 열이 정답인 다른 문항을 깨지 않기 위해서다(§6-8).
    ★ 안정 정렬이라 동점은 원문 순서를 유지한다.
    """
    if not query or len(vals) < 2:
        return vals
    qn = _re.sub(r"\s+", "", str(query))
    items = list(vals.items())
    # ★★ **수치 열끼리만 자리를 바꾼다**(2026-08-24 · r46 실측에서 배웠다).
    #   처음엔 전 열을 정렬했는데 **행 식별자가 뒤로 밀렸다** — 대우건설 미청구공사 행은
    #   `{열1: '미청구공사', 열2: '미청구공사', 채권잔액: 937,999, …}`이라 항목 이름이
    #   `열1`·`열2`에 들어 있다. 그걸 뒤로 보내면 모델이 어느 행인지 못 찾는다.
    #   식별자 열은 **자리를 지키고**, 수치 열이 놓일 자리 안에서만 순서를 바꾼다.
    nidx = [i for i, (_k, x) in enumerate(items) if _num_like(x)]
    if len(nidx) < 2:
        return vals
    order = sorted(nidx, key=lambda i: (-_col_score(items[i][0], qn), i))
    it = iter(order)
    out = {}
    for i, (k, x) in enumerate(items):
        if i in nidx:
            j = next(it)
            out[items[j][0]] = items[j][1]
        else:
            out[k] = x
    return out


def _canon(v, year=None, budget=None, query=None):
    """정본표 → 도구 응답. **핵심행은 전문, 나머지는 라벨만** 준다.

    ★ 크기 예산 안에서만 담는다. 관측 상한 때문에 표 전체를 보내면 잘려서 정작
    핵심행 값이 사라진다(직원 표 2,524자·발행일자별 내역 54행에서 실제로 잘렸다).
    행을 앞에서부터 넣다가 예산을 넘으면 멈추고, 몇 행을 생략했는지 밝힌다.
    """
    keys = [r for r in v["rows"] if r.get("key")] or v["rows"]
    out = {"source": "정본표", "table": v["table"], "section": v["section"],
           "unit": v["unit"], "unit_note": v["unit_note"]}
    # ★ **접수번호를 반드시 넘긴다**(2026-08-11). `values()`가 `출처`를 만들어 두는데
    #   여기서 골라 담지 않아 **정본표 경로에서는 모델에 출처가 가지 않았다.**
    #   주최 테크세션이 접수번호 인용을 시스템 규칙으로 못 박았고(답변 예시가 전부
    #   `(근거: 사업보고서 (2025.12), 접수번호 20260310002820, …)` 형식), 설계 규칙도
    #   "도구가 주는 `출처` 필드를 그대로 쓴다(지어내지 않는다)"고 적어 두었다.
    #   `get_financials`는 넘기고 있었는데 이쪽만 빠져 있었다.
    if v.get("출처"):
        out["출처"] = v["출처"]
    # ★ **표 각주도 같은 이유로 반드시 넘긴다**(2026-08-13). `values()`가 `표_각주`를
    #   만들어 두는데 여기서 안 담아 모델에 가지 않았다 — 위 `출처`와 똑같은 누락이다.
    #   각주는 회사가 표 밑에 직접 쓴 **표의 한계·산출식**이라 표만큼 중요하다
    #   (현대차 "※ 금융부문 … 별도 기재함" 한 줄이 없어서 1-2가 계속 △였다).
    if v.get("표_각주"):
        out["표_각주"] = v["표_각주"]
    # ★ **표 공통값도 같은 이유로 반드시 넘긴다**(2026-08-16). `출처`·`표_각주`가
    #   각각 한 번씩 여기서 누락돼 모델에 안 갔다 — 세 번째다. 행에서 뺀 값이라
    #   여기서 안 담으면 관측에서 **통째로 사라진다**.
    for k in v:
        if k.startswith("표_공통값") or k.startswith("표_계산합계"):
            out[k] = v[k]
    if year:
        out["year"] = year
    # ★★★ **`표_행수`(표의 데이터 행 수)는 두 번 시도해 두 번 기각했다**(2026-08-24 · §6-8).
    #   동기: r49 검색-40에서 모델이 파마리서치 파이프라인 **6개를 정확히 나열**했는데
    #   정답이 `6개`라 숫자 6이 답변에 없어 X가 났다. 개수는 결정론으로 셀 수 있다.
    #     ① 늘 붙이기      394문항 전수 **수치 14개 사라짐 · 정답 위치 62문항 뒤로**
    #                     (지시문 100자가 관측 예산을 먹었다)
    #     ② 개수 질문에만  사라짐 9로 줄었지만 **사라진 곳이 I-4·I-6·D-7 — 전부 계수형**이다.
    #   ★★★ 기각의 결정적 근거: 정답셋에서 **개수를 묻는 정답확정 15건이 전부 계수형**이고
    #     답은 `list_filings`의 **공시 목록 계수**다. 표 행수는 그 답이 아니라 **오답 후보**다.
    #     D-7이 정확히 그렇게 깨졌었다(계수 229 ↔ 전체 235).
    #   ★ 검색-40은 애초에 이 수정으로 안 고쳐진다 — 질문이 "정리해줘"라 개수를 안 묻는다.
    #     정답 `6개`가 질문과 안 맞는 경우다(정답 쪽 축).
    budget = budget or _canon_budget(0, 1)   # 인자 2개다(종전 `(1)`은 호출 시 TypeError)
    cap = ROWS_ALL_CAP.get(v.get("id"))
    if cap:
        budget = min(budget, cap)
    # ★ 크기는 **렌더와 같은 방식**으로 재야 한다. compact JSON으로 재고 `indent=1`로
    #   렌더하면 실제가 훨씬 커져 관측이 잘린다(직원 표가 그렇게 잘려 DS가 사라졌다).
    # ★ 핵심행을 먼저 채우고, **예산이 남으면 나머지 행도 값까지** 보낸다.
    #   종전에는 비핵심행을 항상 라벨만 줬는데, 표가 예산 안에 다 들어가는데도 값을 버렸다.
    #   실측(2-7): capex의 key_rows가 `합 계`뿐이라 DS 474,764·SDC 27,970이 라벨만 가서
    #   모델이 부문별 투자액을 못 답했다(4/4 실패).
    # ★ `key_arith`는 `doctables._arith_key`가 **라벨로 못 잡은 총계 행**을 산술로 찾아
    #   표시한 것이다. 그 표는 종전에 핵심행이 없어 `keys = v["rows"]`로 **전 행이 값까지**
    #   나갔으므로, 총계를 앞으로 올리면서 나머지 행의 값을 잃으면 안 된다(§6-8).
    rest_rows = ([r for r in v["rows"] if r not in keys]
                 if (v.get("id") in ROWS_ALL
                     or any(r.get("key_arith") for r in v["rows"])) else [])
    n_key = len(keys)
    used, shown = _size(out), []
    for r in keys + rest_rows:
        # ★ 정규화를 `_drop_empty` **앞에** 한다. 뒤에 두면 `-`인 값이 이미 지워져
        #   상장 행이 통째로 빈 dict가 된다(실측: SK하이닉스·기아 `상장 행 → {}`).
        vals = r["values"]
        if v.get("id") in _TABLE_ZERO:
            vals = {k: ("0" if (x or "").strip() in _DASH else x) for k, x in vals.items()}
        item = {"label": r["label"],
                "values": _order_cols(
                    _with_unit(_drop_empty(vals), v["unit"], v.get("id")), query)}
        size = (len(r["label"]) + sum(len(x) + 3 for x in item["values"].values())
                if CANON_FORMAT == "md" else _size(item))
        if shown and used + size > budget:
            break
        shown.append(item)
        used += size
    # ★ 핵심행과 나머지를 **필드로 분리**한다. 한 필드에 섞으면 핵심행이 묻힌다 —
    #   실측(1-8): 나머지 행에 값을 주자 모델이 개별 주주(8.51%·1.49%)를 나열하고
    #   정작 `계` 19.84%를 안 썼다(5/6 실패). 값은 주되 무엇이 핵심인지는 남긴다.
    if CANON_FORMAT == "md" and shown:
        # ★ md에서도 **핵심행과 나머지를 갈라** 표 두 개로 낸다(2026-08-10).
        #   종전 md 경로는 한 표로 합쳤는데, 위 주석의 실패(1-8: 개별 주주를 나열하고
        #   정작 `계` 19.84%를 안 씀, 5/6 실패)가 정확히 그 형태다.
        #   형식을 바꾸는 것과 **구조를 버리는 것**은 다르다 — 구조는 유지한다.
        out["핵심행"] = _md_table(shown[:n_key], v["unit_note"])
        if shown[n_key:]:
            out["그 밖의 행(값 포함)"] = _md_table(shown[n_key:], "")
