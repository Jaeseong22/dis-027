        #                 명시되어 있습니다**" — 필드를 보고도 앞의 영문 약칭을 골랐다
        #     D-3 셀트리온 보고자·특별관계자를 하나씩 나열하다 잘렸다(`열 합계`에
        #                 72,698,477이 있는데 안 썼다)
