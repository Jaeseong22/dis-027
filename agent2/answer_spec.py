#: **계수 질의** — "몇 번/몇 건 있었어?". 답이 숫자 하나뿐인 질문이다.
#:
#: ★★ 여기에는 요건을 붙이지 않는다(2026-08-17). 이 모듈의 요건은 **서술형 답변이
#:   불완전한 것**을 고치려고 만들었다(1-7 발행주식수·1-11 종속회사·2-4 주요사업).
#:   "몇 번 발행되었어?"에 지분구조·발행주식총수를 요구하는 것은 범주 착오이고,
#:   `prompt_hint`가 "확인 안 되는 항목은 그렇다고 적으십시오"라 모델이 **묻지도 않은
#:   것을 부인**하게 만든다. 그 부작용이 두 갈래로 실측됐다:
#:
#:     B-1 셀트리온  `shares` 요건 → 부인 → `loop.GATE_ONLY_ON_DENIAL`이 완료게이트를
#:                  깨우고 `주식의 총수` 정본표를 주입 → 모델이 답을 다시 쓰며 계수 14를 버렸다
#:     D-7 삼성전자  `ownership` 요건 → `retry_hint` 재생성이 답을 통째로 덮어썼다
#:                  ("[지분구조] … 공시에서 확인되지 않습니다"만 남고 2,627이 사라졌다).
#:                  이 문항은 그 전 12회차 내내 O였다 — **가끔 터지지만 터지면 정답이 없어진다.**
#:
#:   전수(평가셋 115문항): 계수 질의인데 요건이 붙던 문항은 **D-7·I-8·I-9 3문항 ×
#:   4사 = 12건**이다(B-1은 `shares` 트리거에서 `자기주식`을 빼면서 이미 빠졌다).
#:   ★ 어휘를 지어내지 않았다 — 평가셋 계수 문항 전수에서 실제로 쓰이는 표현이다.
_COUNT_Q = re.compile(r"몇\s*(번|건|개|차례)|횟수")


def classify(question):
    """질의 → 해당하는 유형 목록. **결정론 키워드 매칭**이다(LLM 분류 안 씀).

    ★ 계수 질의는 어떤 유형에도 걸리지 않는다 — 위 `_COUNT_Q` 주석 참조.
    """
    q = (question or "").lower()
    if _COUNT_Q.search(q):
        return []
    return [s for s in SPECS if any(t.lower() in q for t in s.triggers)]


def requirements(question):
    """질의에 걸리는 요건 전부(중복 라벨 제거)."""
    seen, out = set(), []
    for s in classify(question):
        for r in s.requires:
            if r.label not in seen:
                seen.add(r.label)
                out.append((s.name, r))
    return out


def missing(question, answer):
    """답변에서 빠진 요건 목록. 결정론 어휘 검사."""
    a = (answer or "")
    # 정보가 없다고 정직하게 답한 경우는 요건을 강제하지 않는다.
    if re.search(r"확인되지\s*않|확인할\s*수\s*없|찾을\s*수\s*없", a) and len(a) < 200:
        return []
    return [(name, r) for name, r in requirements(question)
            if not any(k in a for k in r.any_of)]


def prompt_hint(question):
    """생성 시점에 프롬프트로 넣을 요건 안내. 없으면 빈 문자열."""
    reqs = requirements(question)
    if not reqs:
        return ""
    lines = ["이 유형의 답변에 반드시 포함해야 할 항목입니다 "
             "(근거에서 확인되는 것만 쓰고, 확인 안 되는 항목은 그렇다고 적으십시오):"]
    for name, r in reqs:
        lines.append(f"  · [{name}] {r.label}")
    return "\n".join(lines)


def retry_hint(question, answer):
    """검증 후 재생성용. 빠진 항목만 짚는다. 없으면 빈 문자열."""
    miss = missing(question, answer)
    if not miss:
        return ""
    # ★★ 2026-08-11 문구 교체 — 종전 문구가 **답변을 통째로 버리게 만들었다.**
    #   종전: "빠진 항목만 보완해 **다시 작성**하십시오"
    #   → 모델이 "빠진 항목에 **대해서만** 답하기"로 읽었다. 실측(step6 1-11):
    #       #21 삼성전자  이전 O → X
    #         "전년 대비 증감에 대한 정보는 확인할 수 없습니다. 따라서 답변드릴 수 없습니다."
    #         → 합계 308·상장 1·비상장 307·주요 158을 **전부 잃었다**
    #     1-11이 8.0 → 3.0으로 무너졌고 전체가 −14.5문항이었다.
    #   "다시 작성"이 전체 재작성인지 부분 보완인지 모호했던 것이 원인이다.
    #   → **앞선 답변을 그대로 두고 덧붙이라**고 명시한다. 문구는 긍정형(topic/93).
    lines = ["앞선 답변은 그대로 유지하십시오. 거기에 아래 항목만 덧붙여 "
             "**전체 답변을 다시 한 번 완성해** 주십시오. "
             "이미 적은 수치와 출처는 하나도 빠뜨리지 않고 그대로 포함합니다. "
             "덧붙일 항목이 근거에 없으면 그 항목에만 "
             "'공시에서 확인되지 않습니다'라고 적습니다:"]
    for name, r in miss:
        lines.append(f"  · [{name}] {r.label}")
    return "\n".join(lines)


