from collections import namedtuple

#: 루브릭 항목 하나.
#:   kind="num"   value+unit(+scope) 수치. 단위 환산 후 대조한다.
#:   kind="text"  any_of 중 하나라도 답변에 있으면 통과(서술형 커버 포인트).
#:   kind="forbid" 나오면 안 되는 값/문자열(대표적 오답을 명시적으로 잡는다).
Check = namedtuple("Check", "kind label value unit scope weight any_of")
Check.__new__.__defaults__ = ("num", "", None, "", "연결", 1, ())

Item = namedtuple("Item", "id reference checks sources note")
Item.__new__.__defaults__ = ("", "", (), "", "")


def num(label, value, unit, scope="연결", weight=1):
    return Check("num", label, value, unit, scope, weight, ())


def text(label, *any_of, weight=1):
    return Check("text", label, None, "", "", weight, tuple(any_of))


def absent(label, *any_of, weight=1):
    """**부재 선언이 정답**인 항목. 예: 전환사채가 없다는 사실을 밝혀야 하는 경우.

    일반 커버 체크는 부정문 안의 매칭을 인정하지 않는데(그래야 "확인되지 않음"으로
    점수를 따는 걸 막는다), 이 항목은 반대로 **부재를 밝혀야** 통과다.
    둘을 구분하지 않으면 정답을 오답 처리한다(실측: "전환사채는 해당 없습니다"를 막았다).
    """
    return Check("absent", label, None, "", "", weight, tuple(any_of))


def forbid(label, value=None, unit="", *any_of):
    return Check("forbid", label, value, unit, "", 1, tuple(any_of))


